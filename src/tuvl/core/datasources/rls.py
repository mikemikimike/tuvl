"""PostgreSQL Row-Level Security (RLS) policy generator for tenant tables.

Generates idempotent SQL that:

1. ``ALTER TABLE ... ENABLE ROW LEVEL SECURITY`` on every tenant-scoped
   table.
2. Creates a ``tuvl_tenant_isolation`` policy on each table that compares
   ``tenant_id`` to the per-transaction GUC
   ``app.current_tenant_id`` (set by the session ``after_begin`` hook
   installed in :func:`tuvl.core.datasources.postgres._bind_tenant_isolation`).

The output is plain SQL so an operator can review it before applying — the
CLI command :mod:`tuvl.cli.commands.db` exposes both ``generate-rls`` (print
to stdout) and ``check-rls`` (connect and verify policies exist).

This module is intentionally **synchronous** and dependency-free: it only
reads the in-memory ``MODEL_REGISTRY`` plus the static list of system
tenant tables, so it can run before any engine is built.
"""

from __future__ import annotations

# System-level tables that carry tenant_id but are not user-defined.
# Keep in sync with ``DynamicTenantModel`` subclasses in
# ``tuvl.core.models.system``.
_SYSTEM_TENANT_TABLES: tuple[str, ...] = (
    "tuvl_system_vector_store",
    "tuvl_system_workflow_instances",
    "tuvl_system_artifacts",
)

# Name of the policy we install — used both for CREATE and for the
# existence check in ``check-rls``.  Including a tuvl-specific prefix
# avoids colliding with operator-authored policies on the same tables.
TUVL_POLICY_NAME = "tuvl_tenant_isolation"


def _user_tenant_tables() -> list[str]:
    """Return the table names of every user-defined model that carries
    a ``tenant_id`` column (i.e. every model in ``MODEL_REGISTRY`` once
    ``_inject_tenant_columns_into_registry`` has run)."""
    from tuvl.core.models.loader import MODEL_REGISTRY

    tables: list[str] = []
    for model_cls in MODEL_REGISTRY.values():
        table = getattr(model_cls, "__table__", None)
        if table is None or "tenant_id" not in table.c:
            continue
        tables.append(table.name)
    return sorted(set(tables))


def tenant_table_names() -> list[str]:
    """Return the full sorted list of tables that should have RLS enabled."""
    return sorted(set(_SYSTEM_TENANT_TABLES) | set(_user_tenant_tables()))


def generate_rls_sql() -> str:
    """Return idempotent SQL enabling RLS on every tenant-scoped table.

    The generated statements are safe to re-run: ``ENABLE`` is a no-op
    when already enabled, and the policy is recreated via ``DROP POLICY
    IF EXISTS`` + ``CREATE POLICY`` so the SQL converges to the
    documented contract regardless of any prior state.
    """
    lines: list[str] = [
        "-- TUVL multi-tenant Row-Level Security bootstrap",
        "-- Generated by `tuvl generate rls`.  Safe to re-run.",
        "-- The policy compares each row's tenant_id to the per-transaction",
        "-- GUC app.current_tenant_id, which the TUVL session `after_begin`",
        "-- hook sets via `SET LOCAL`.",
        "",
    ]
    for table in tenant_table_names():
        lines.append(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY;")
        lines.append(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY;")
        lines.append(f"DROP POLICY IF EXISTS {TUVL_POLICY_NAME} ON {table};")
        lines.append(
            f"CREATE POLICY {TUVL_POLICY_NAME} ON {table}\n"
            f"    USING (tenant_id = current_setting('app.current_tenant_id', true))\n"
            f"    WITH CHECK (tenant_id = current_setting('app.current_tenant_id', true));"
        )
        lines.append("")
    return "\n".join(lines)


async def find_tables_missing_rls_policy() -> list[str]:
    """Connect to the primary datasource and return the tenant tables that
    do **not** have the ``tuvl_tenant_isolation`` policy installed.

    Used by the ``tuvl verify rls`` CLI command and (optionally) by the
    bootstrap warning to surface misconfigurations at startup.  Returns
    an empty list if every tenant table is correctly policed.
    """
    from sqlalchemy import text

    from tuvl.core.datasources.postgres import (
        _PRIMARY_DS,
        get_session_factory,
    )

    factory = get_session_factory(_PRIMARY_DS, is_write=False)
    expected = tenant_table_names()
    missing: list[str] = []
    async with factory() as session:
        conn = await session.connection()
        result = await conn.execute(
            text(
                "SELECT tablename FROM pg_policies "
                "WHERE policyname = :pname AND tablename = ANY(:tables)"
            ),
            {"pname": TUVL_POLICY_NAME, "tables": expected},
        )
        present = {row[0] for row in result.fetchall()}
    for table in expected:
        if table not in present:
            missing.append(table)
    return missing
